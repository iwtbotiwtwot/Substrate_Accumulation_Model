#!/usr/bin/env python3
"""Generate volumes/I/concept_notes/REGISTER.md from register.json, reading tier, reproducibility, independence, ideas and edges from the Courtroom II CASE.json files it names. Standard library."""
import json, os, sys
HERE=os.path.dirname(os.path.abspath(__file__)); NOTES=os.path.join(HERE,'..','concept_notes'); reg=json.load(open(os.path.join(NOTES,'register.json'))); CII=reg['courtroom_ii']
def case_info(cid):
    p=os.path.join(CII,cid,'CASE.json')
    if not os.path.exists(p): return {"missing": True}
    c=json.load(open(p)); return {"tier":c.get('tier'),"R":c.get('reproducibility'),"I":c.get('independence'),"ideas":[i['id'] for i in c.get('ideas',[])],"edges":[f"{e['type']}: {e['from'][:40]} -> {e['to'][:40]}" for e in c.get('edges',[])],"approved":c.get('reviewed_and_approved')}
L=[]; w=L.append
w("# Volume I — statements register\n")
w("Generated by `tools/statements_register.py` from `register.json` and the Courtroom II case files. One row per formal statement: what it says, its type, which note worked it out, which case verified it and to what tier, which volume it belongs to (exact placement sorted out later, Sean Brady 2026-10-30), and its place in the Research Web. Rows marked 'proposed' are the lead's proposals for work not yet done. Nothing here is a claim.\n")
w("| # | statement (short) | type | note | case(s) · tier · R · I | decider | volume |\n|---|---|---|---|---|---|---|")
missing=[]; cases_seen=set()
for i,s in enumerate(reg['statements'],1):
    infos=[]
    for cid in s['cases']:
        ci=case_info(cid); cases_seen.add(cid)
        if ci.get('missing'): missing.append(cid); infos.append(f"{cid} (MISSING)")
        else: infos.append(f"{cid} · {ci['tier']} · {ci['R']} · {ci['I']}")
    short=s['statement'][:110]+('…' if len(s['statement'])>110 else '')
    casecell='<br>'.join(infos) if infos else (f"proposed: {s['proposed_case']}" if s.get('proposed_case') else '— (statement only)')
    w(f"| {i} | {short} | {s['type']} | {s['note']} | {casecell} | {s['decider'][:90]} | {s['volume']} |")
w("\n## Detail\n")
for i,s in enumerate(reg['statements'],1):
    w(f"### {i}. `{s['id']}`\n")
    w(f"**Statement.** {s['statement']}\n")
    w(f"**Author.** {s['author']}. **Type.** {s['type']}. **Note.** {s['note']}.\n")
    for cid in s['cases']:
        ci=case_info(cid)
        if not ci.get('missing'): w(f"**Case** `{cid}`: tier {ci['tier']}, reproducibility {ci['R']}, independence {ci['I']}, approved {ci['approved']}. Research Web ideas: {', '.join(ci['ideas']) or 'none'}. Edges: {'; '.join(ci['edges']) or 'none'}.\n")
    w(f"**Decider.** {s['decider']}\n")
    w(f"**Volume.** {s['volume']}. {s['placement_note']}.\n")
    if s.get('proposed_case'): w(f"**Proposed case (not yet run).** `{s['proposed_case']}`.\n")
# coverage
all_cases=sorted(d for d in os.listdir(CII) if d.startswith('voli_') for _ in [0]) if os.path.isdir(CII) else []
voli_cases=sorted(f"{camp}/{c}" for camp in os.listdir(CII) if camp.startswith('voli_') for c in os.listdir(os.path.join(CII,camp)))
w("## Coverage\n")
w(f"Statements: {len(reg['statements'])}; with a verifying case: {sum(1 for s in reg['statements'] if s['cases'])}; statement-only (pictures and definitions by direction): {sum(1 for s in reg['statements'] if not s['cases'])}. Proposed cases not yet run: {sum(1 for s in reg['statements'] if s.get('proposed_case'))}.\n")
w(f"Volume I cases in Courtroom II: {len(voli_cases)}; referenced by a statement: {len(cases_seen & set(voli_cases))}; not referenced: {sorted(set(voli_cases)-cases_seen) or 'none'}.\n")
if missing: w(f"Referenced cases missing from Courtroom II: {missing}\n")
w("\nDirected by Sean Brady. Executed with Claude Code. AI-assisted writing.")
open(os.path.join(NOTES,'REGISTER.md'),'w').write("\n".join(L)+"\n"); print("register written:", len(reg['statements']), "statements;", len(voli_cases), "volume cases;", "missing" if missing else "all cases found")
