# Process only normal text. Protected math is never traversed a second time.
def apply_text(s):
    for a,b in sorted(phrases.items(),key=lambda kv:-len(kv[0])):
        # Discard replacements inside an existing math fragment.
        parts=re.split(r'(\$[^$]*\$)',s)
        s=''.join(part if part.startswith('$') else part.replace(a,b) for part in parts)
    # Isolated source variables in prose need their own mathematical role.
    varmap={'π':r'\pi','α':r'\alpha','β':r'\beta','τ':r'\tau','ρ':r'\rho','ε':r'\varepsilon','μ':r'\mu','η':r'\eta','ν':r'\nu','λ':r'\lambda'}
    for a,b in varmap.items():
        parts=re.split(r'(\$[^$]*\$)',s)
        s=''.join(part if part.startswith('$') else re.sub(r'(?<![\w])'+a+r'(?![\w])',lambda m:'$'+b+'$',part) for part in parts)
    parts=re.split(r'(\$[^$]*\$)',s)
    s=''.join(part if part.startswith('$') else re.sub(r"(?<![\w'])(([BCDEFGHJKLMNPQRSTUVXYZbcdefghijklmnopqrstuvwxyz]))(?![\w])",lambda m:'$'+m.group(1)+'$',part) for part in parts)
    return s

